void load_resource_file(int res_index, const char* filename) // loads file directly into res_data buffer
{
    extern std::vector<uint8_t> getFileContents(const std::string&);
    std::vector<uint8_t> data = getFileContents(filename);
    if (data.empty()) {
        printf("Resource not found: %s\n", filename);
        return;
    }
    size_t len = data.size();
    if (len > 0x7d00) len = 0x7d00;
    memcpy(res_data[res_index], data.data(), len);
    printf("Loaded %s (%zu bytes)\n", filename, len);
}

