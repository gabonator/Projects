// --- Entity structure ---
// Entities are 23 (0x17) bytes each, starting at ds:0x1B8A
// Terminated by an entity with bit 7 set in flags byte

#pragma pack(push, 1)
struct Entity {
    uint8_t flags;       // +0: bit7=end_marker, bit5=?, bit1=active, bit0=visible
    uint8_t direction;   // +1: movement direction / subtype
    uint8_t zLayer;      // +2: z-order for rendering (1-7)
    uint8_t heightOfs;   // +3: height offset for terrain
    uint8_t dirFlag;     // +4: direction flag / animation state
    uint16_t x;          // +5: X position (screen coords, 0x14..0xEC)
    uint16_t y;          // +7: Y position (map-relative, 0..0x3FF wrapping)
    uint8_t spriteW;     // +9: sprite width
    uint8_t spriteH;     // +10: sprite height
    uint8_t drawOfsY;    // +11: Y draw offset
    uint8_t drawOfsX;    // +12: X draw offset
    uint16_t spriteSheet;// +13: sprite sheet index -> lookup at offset 38120
    uint16_t spriteData; // +15: sprite data offset
    uint8_t colorMask;   // +17: color/palette mask
    uint8_t type;        // +18: entity type (1-35, indexes into handler jump table)
    union {
        uint16_t param;  // +19: type-specific parameter (word access)
        struct { uint8_t param1; uint8_t param2; }; // +19,+20: byte access
    };
    uint8_t hitPoints;   // +21: hit points / lifetime counter
    uint8_t animFrame;   // +22: animation frame counter
};
#pragma pack(pop)
static_assert(sizeof(Entity) == 23, "Entity must be 23 bytes");

