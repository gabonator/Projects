// Access entity by si offset: entities[(si - ENTITY_BASE) / ENTITY_SIZE]
inline Entity& ent(uint16_t si_val) {
    assert(si_val >= ENTITY_BASE && "ent() called with si below ENTITY_BASE");
    unsigned idx = (si_val - ENTITY_BASE) / ENTITY_SIZE;
    assert(idx <= ENTITY_SLOTS && "ent() called with si beyond entity array");
    return entities[idx];
}

